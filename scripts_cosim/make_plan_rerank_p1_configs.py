#!/usr/bin/env python3
"""plan_rerank_v1 Phase 1: write the selector configs (experiments/plan_rerank_v1_*.yaml). Edit this, not the yamls.

Arms: variant a (S + learned residual) and b (direct scorer), each with message passing and as its MP-OFF twin, on the pool of each
base (gnn_eng = accel-replica-v1-gnn-eng-g4-seed1, gnn_eng_physmp = accel-replica-v1-gnn-eng-physmp-g3-seed1). Same recipe, pool,
features and split for every arm; the twin differs only by GNN_DISABLE_MESSAGE_PASSING=1. Seeds via run_experiment.py --seed N; the
run name (and so the checkpoint) is plan-rerank-v1-<base>-sel<variant>[twin]-seed<N>, the name the gate harness serves.
"""
from __future__ import annotations

from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
POOL = "/share/nikola.lukic/plan_rerank/branchpool_981f263a/pool"
SPLIT = "/share/nikola.lukic/accel_prod/20261010_061132/cache_run/split.json"
BASES = {"gnn_eng": ("g4", "/home/nikola.lukic/gnn-herosim/models/accel-replica-v1-gnn-eng-g4-seed1.pt"),
         "gnn_eng_physmp": ("physmp_g3", "/home/nikola.lukic/gnn-herosim/models/accel-replica-v1-gnn-eng-physmp-g3-seed1.pt")}
RECIPE = {"epochs": 100, "learning-rate": 0.001, "weight-decay": 0.0001, "embedding-dim": 64, "hidden-dim": 64, "num-layers": 3,
          "dropout": 0.1, "tau-rel": 0.05, "weight-cap": 1.0, "pools-per-step": 16}
CACHE = "simulation_data/graphs_cache_accel_replica_v1_psv5_inf"


def config(base: str, variant: str, twin: bool, smoke: bool = False) -> dict:
    tag, ck = BASES[base]
    name = f"plan-rerank-v1-{base.replace('_', '-')}-sel{variant}{'twin' if twin else ''}" + ("-smoke" if smoke else "")
    args = {"pool-train": f"{POOL}/pool_{tag}_train.jsonl", "pool-val": f"{POOL}/pool_{tag}_val.jsonl", "split": SPLIT,
            "base-checkpoint": ck, "variant": variant, **RECIPE}
    if smoke:
        args.update({"epochs": 1, "max-train-pools": 64, "max-val-pools": 32, "smoke": None})
    return {
        "trainer": "plan_selector",
        "description": (f"plan_rerank_v1 Phase 1 selector, variant {variant} ({'S + learned residual' if variant == 'a' else 'direct scorer'}), "
                        f"{'MP-OFF twin' if twin else 'message passing'}, pool of {Path(ck).stem}" + (" -- SMOKE (wiring only, never served in a gate)" if smoke else "")),
        "lineage": "plan_rerank_v1",
        "cache_dir": CACHE,
        "unset_env": ["GNN_DISABLE_MESSAGE_PASSING"] if not twin else [],
        "env": {"GNN_DISABLE_MESSAGE_PASSING": "1"} if twin else {},
        "args": args,
        "wandb": {"project": "gnn-plan-rerank-v1", "run_name": name,
                  "tags": ["plan-rerank-v1", "phase1", f"sel{variant}", "twin" if twin else "mp", base] + (["smoke"] if smoke else [])},
    }


def main() -> int:
    out = {}
    for base in BASES:
        for variant in ("a", "b"):
            for twin in (False, True):
                out[f"plan_rerank_v1_{base}_sel{variant}{'twin' if twin else ''}.yaml"] = config(base, variant, twin)
    out["plan_rerank_v1_gnn_eng_sela_smoke.yaml"] = config("gnn_eng", "a", False, smoke=True)
    for fname, cfg in out.items():
        if not cfg["unset_env"]:
            cfg.pop("unset_env")
        if not cfg["env"]:
            cfg.pop("env")
        head = "# Generated by scripts_cosim/make_plan_rerank_p1_configs.py -- edit the generator, not this file.\n"
        (REPO / "experiments" / fname).write_text(head + yaml.safe_dump(cfg, sort_keys=False))
        print(fname)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
